function toWall(item: Promo): StandaloneWall {
  return {
    id: item.id,
    type: "video",
    src: item.src,
    width: WALL_WIDTH,
    height: WALL_HEIGHT,
    objectFit: "cover",
    objectPosition: item.objectPosition ?? "50% 50%",
    poster: item.src.replace(/\.mp4$/, ".jpg"),
  };
}

export const standaloneSubCases: StandaloneSubCase[] = PROMOS.map((item) => ({
  id: item.id,
  title: item.title,
  description: item.description,
  walls: [toWall(item)],
}));

export const standaloneFaceWalls: StandaloneWall[] = standaloneSubCases.map(
  (item) => item.walls[0],
);

